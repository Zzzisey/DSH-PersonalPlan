import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
let revision = 'unknown'
try {
  revision = execFileSync('git', ['rev-parse', '--short=8', 'HEAD'], { encoding: 'utf8' }).trim()
  try {
    execFileSync('git', ['diff', '--quiet', '--ignore-submodules', 'HEAD'])
  } catch {
    revision += '.dirty'
  }
} catch {
  // Source archives may not contain .git; keep the absence explicit.
}

const source = `// Generated by scripts/generate-build-info.mjs; do not edit.\n`
  + `export const BUILD_VERSION = ${JSON.stringify(pkg.version)}\n`
  + `export const BUILD_REVISION = ${JSON.stringify(revision)}\n`
  + `export const BUILD_ID = \`${'${BUILD_VERSION}'}+${'${BUILD_REVISION}'}\`\n`

mkdirSync('src/generated', { recursive: true })
writeFileSync('src/generated/build-info.ts', source)
console.log(`build info: ${pkg.version}+${revision}`)
